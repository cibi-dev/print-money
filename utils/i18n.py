def set_idioma(idioma: str):
    """Cambia el idioma activo globalmente."""
    global _idioma_actual
    _idioma_actual = idioma if idioma in ("es", "en") else "es"


def get_idioma() -> str:
    """Retorna el idioma activo."""
    return _idioma_actual


def T(clave: str, **kwargs) -> str:
    """Obtiene la traducción de una clave. Acepta kwargs para .format()."""
    entry = STRINGS.get(clave)
    if entry is None:
        return clave  # Fallback: retornar la clave misma
    valor = entry.get(_idioma_actual, entry.get("es", clave))
    if isinstance(valor, list):
        return valor  # Para listas como meses
    if kwargs:
        try:
            return valor.format(**kwargs)
        except (KeyError, IndexError):
            return valor
    return valor
